# ---------------------------------------------------------------------------
# 5. End-to-end CalculiX parse check
# ---------------------------------------------------------------------------


def _frd_node_numbers(frd_path: Path) -> list[int]:
    """Node numbers from the FRD nodal-coordinate (``2C``) block.

    Without ``OUTPUT=2D`` CalculiX expands a shell deck to its 3D counterpart
    for output, so the FRD node numbers do not equal the input mesh labels.
    Read them from the file instead of assuming a mapping.
    """
    numbers: list[int] = []
    in_nodes = False
    for line in frd_path.read_text().splitlines():
        if line.strip().startswith("2C"):
            in_nodes = True
            continue
        if in_nodes and line.startswith(" -3"):
            break
        if in_nodes and line.startswith(" -1"):
            numbers.append(int(line[3:13]))
    return numbers


def test_dynamic_fsi_deck_runs_in_ccx(tmp_path: Path) -> None:
    """The emitted deck must run in the real binary and write a DISP block."""
    ccx_bin = ccx_bin_or_skip()
    inp = tmp_path / "fsi.inp"
    write_ccx_mesh(
        _build_mesh(),
        str(inp),
        properties=_properties(),
        boundary_nodeset="clamped",
        solver_type="DynamicFSI",
        fsi_interface_nodeset=INTERFACE,
        dt=5e-3,
        t_end=1e-2,
    )

    completed = run_ccx(inp, ccx_bin)
    assert completed.returncode == 0, (
        f"ccx failed (rc={completed.returncode}):\n{completed.stdout[-2000:]}"
    )

    frd = inp.with_suffix(".frd")
    frd_nodes = _frd_node_numbers(frd)
    assert frd_nodes, f"no nodal block in {frd}"
    disp = parse_frd_disp(frd, frd_nodes)
    assert set(disp) == set(frd_nodes), (
        f"FRD has no complete DISP block: parsed {len(disp)} of {len(frd_nodes)} nodes"
    )
