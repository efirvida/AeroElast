# ---------------------------------------------------------------------------
# Small 2x2 quad shell mesh (mirrors tests/test_ccx_writer_ids.py)
# ---------------------------------------------------------------------------


def _build_mesh(*, split_elements: bool = False) -> MeshModel:
    """A 2x2 quad plate strip with a clamped edge and an interface edge."""
    Node._id_counter = 0
    MeshElement._id_counter = 0

    mesh = MeshModel()
    grid: dict[tuple[int, int], Node] = {}
    for j in range(3):
        for i in range(3):
            node = Node([float(i), float(j), 0.0], geometric_node=False)
            mesh.add_node(node)
            grid[(i, j)] = node

    elements: list[MeshElement] = []
    for j in range(2):
        for i in range(2):
            element = MeshElement(
                nodes=[grid[(i, j)], grid[(i + 1, j)], grid[(i + 1, j + 1)], grid[(i, j + 1)]],
                element_type=ElementType.quad,
            )
            mesh.add_element(element)
            elements.append(element)

    mesh.add_node_set(NodeSet("clamped", {n for n in mesh.nodes if np.isclose(n.y, 0.0)}))
    mesh.add_node_set(NodeSet(INTERFACE, {n for n in mesh.nodes if np.isclose(n.y, 2.0)}))

    if split_elements:
        # Two element sets so two *MATERIAL blocks are emitted.
        mesh.add_element_set(ElementSet("plate_a", {elements[0]}))
        mesh.add_element_set(ElementSet("plate_b", set(elements[1:])))
    else:
        mesh.add_element_set(ElementSet("plate", set(mesh.elements)))
    return mesh


def _properties() -> dict:
    return {"plate": ShellProperty(material=STEEL, thickness=THICKNESS)}


def _write_fsi(tmp_path: Path, stem: str = "fsi", **kwargs) -> Path:
    inp = tmp_path / f"{stem}.inp"
    write_ccx_mesh(
        _build_mesh(),
        str(inp),
        properties=_properties(),
        boundary_nodeset="clamped",
        solver_type="DynamicFSI",
        fsi_interface_nodeset=INTERFACE,
        **kwargs,
    )
    return inp


# ---------------------------------------------------------------------------
# 1. Adapter step cards
# ---------------------------------------------------------------------------


def test_dynamic_fsi_deck_emits_adapter_cards(tmp_path: Path) -> None:
    """nlgeom/direct increments, the time line and the zero *CLOAD block."""
    inp = _write_fsi(tmp_path, nlgeom=True, direct_increments=True, dt=1e-2, t_end=0.02)
    text = inp.read_text()

    assert "*STEP, NLGEOM, INC=1000000" in text
    assert "*DYNAMIC, DIRECT" in text
    assert "1.000000E-02, 2.000000E-02" in text

    # One zero load line per spatial DOF, on the emitted (upper, N-prefixed) set.
    for dof in (1, 2, 3):
        assert f"{INTERFACE_SET}, {dof}, 0.0" in text
    assert text.count(f"{INTERFACE_SET}, ") == 3


def test_dynamic_fsi_output_frequency_default_and_override(tmp_path: Path) -> None:
    """Output requests default to the writer's ``FREQUENCY=10`` and honour an override."""
    default_text = _write_fsi(tmp_path, stem="fsi_default").read_text()
    assert "*NODE FILE, FREQUENCY=10" in default_text
    assert "*EL FILE, FREQUENCY=10" in default_text

    override_text = _write_fsi(tmp_path, stem="fsi_freq", output_frequency=1).read_text()
    assert "*NODE FILE, FREQUENCY=1" in override_text
    assert "*EL FILE, FREQUENCY=1" in override_text


# ---------------------------------------------------------------------------
# 2. Rayleigh damping inside every *MATERIAL block
# ---------------------------------------------------------------------------


def test_dynamic_fsi_rayleigh_damping_in_every_material(tmp_path: Path) -> None:
    inp = tmp_path / "fsi.inp"
    write_ccx_mesh(
        _build_mesh(split_elements=True),
        str(inp),
        properties={
            "plate_a": ShellProperty(material=STEEL, thickness=THICKNESS),
            "plate_b": ShellProperty(material=ALUMINIUM, thickness=THICKNESS),
        },
        boundary_nodeset="clamped",
        solver_type="DynamicFSI",
        fsi_interface_nodeset=INTERFACE,
        rayleigh_damping=(0.5, 1e-3),
    )
    text = inp.read_text()
    card = "*DAMPING, ALPHA=5.000000E-01, BETA=1.000000E-03"

    material_blocks = text.split("*MATERIAL")[1:]
    assert len(material_blocks) == 2, text
    for block in material_blocks:
        assert card in block
    assert text.count(card) == 2


def test_rayleigh_damping_not_emitted_for_other_solver_types(tmp_path: Path) -> None:
    """Other solver types must not gain a *DAMPING card from the new argument."""
    inp = tmp_path / "modal.inp"
    write_ccx_mesh(
        _build_mesh(),
        str(inp),
        properties=_properties(),
        boundary_nodeset="clamped",
        solver_type="Modal",
        num_modes=5,
        rayleigh_damping=(0.5, 1e-3),
    )
    assert "*DAMPING" not in inp.read_text()


