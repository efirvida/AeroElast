"""The CalculiX ``DynamicFSI`` deck used by the preCICE adapter.

The CalculiX-preCICE adapter reuses CalculiX's point-force data structures for
the coupling interface, so the deck must load *every* node of the FSI interface
node set in *every* spatial direction: "it is necessary to load all nodes of
the node set, which defines the FSI interface in CalculiX, in each spatial
direction ... the values of these initial forces can (and should) be chosen to
zero" (calculix-adapter ``docs/configure.md``).  The adapter also drives a
``*DYNAMIC`` step, and the standard adapter deck looks like::

    *STEP, NLGEOM, INC=1000000
    *DYNAMIC
     0.01, 5.0
    *BOUNDARY
    *CLOAD
     Ninterface, 1, 0.0
     Ninterface, 2, 0.0
     Ninterface, 3, 0.0

``write_ccx_mesh`` grew a ``DynamicFSI`` solver-type branch that emits exactly
that deck (plus an optional per-material Rayleigh ``*DAMPING`` card).  This
module pins the emitted cards, the argument validation, and -- as a regression
guard -- that the pre-existing ``Modal`` and ``LinearStatic`` decks are
byte-identical to the output captured *before* the branch existed.
"""

